tx(() => {
  NOVELS.forEach((n, ni) => {
    const slug = n.title.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
    if (db.prepare('SELECT 1 FROM novels WHERE slug = ?').get(slug)) return;
    const r = db.prepare(`INSERT INTO novels (slug, title, alt_titles, author, original_language, year, status, description, tags, owner_id, views, created_at, updated_at)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, unixepoch() - ?, unixepoch() - ?)`)
      .run(slug, n.title, n.alt, n.author, n.lang, n.year, n.status, n.description, n.tags, owner, 500 + ni * 1700, 86400 * 30, ni * 3600);
    const id = Number(r.lastInsertRowid);
    setNovelGenres(id, n.genres.map(genreId).filter(Boolean));
    const ins = db.prepare('INSERT INTO chapters (novel_id, number, title, content, word_count, views, created_at) VALUES (?, ?, ?, ?, ?, ?, unixepoch() - ?)');
    for (let c = 1; c <= n.chapters; c++) {
      const html = textToHtml(makeChapter(c + ni));
      ins.run(id, c, n.titles[(c - 1) % n.titles.length], html, wordCount(html), Math.max(3, 200 - c * 7), (n.chapters - c) * 43200 + ni * 3600);
    }
    console.log(`Added “${n.title}” with ${n.chapters} chapters`);
  });
});
