function makeChapter(seed, paragraphs = 14) {
  const out = [];
  for (let i = 0; i < paragraphs; i++) out.push(SCENES[(seed * 7 + i * 3) % SCENES.length]);
  out.splice(Math.floor(paragraphs / 2), 0, '***');
  return out.join('\n\n');
}

